function evidenceAudit(sources: ResearchSource[], figures: ResearchFigure[]): string {
  const sourceText = sources.map((item, index) =>
    `資料${index + 1}「${item.title}」は${item.publisher}が公開し、${item.note} 確認日は${item.accessed}である。`
  ).join("");
  const figureText = figures.map((item, index) =>
    `図${index + 1}「${item.alt}」は現在の外観資料であり、写真だけから成立年代、作者、信仰内容を決定しない。`
  ).join("");
  return `資料監査では、行政台帳、寺院公式説明、学術論文、現地写真の作成主体と目的を分け、同じ説明の転載を独立証拠として数えない。${sourceText}${figureText}主張ごとに対象年代、根拠資料、確度、最終確認日を結び、後世の案内文が過去の出来事を説明する場合は、出来事の年代と説明成立の年代を別に保存する。`;
}

function makeArticle(
  meta: Omit<ResearchArticle, "sections" | "sources">,
  headings: string[],
  paragraphs: string[][],
  figures: ResearchFigure[],
  sources: ResearchSource[],
  method: string,
): ResearchArticle {
  return {
    ...meta,
    sections: headings.map((heading, index) => ({
      heading: `${index + 1}　${heading}`,
      paragraphs: [
        ...paragraphs[index],
        ...(index === headings.length - 1 ? [method, evidenceAudit(sources, figures), authorDisclosure] : []),
      ],
      figure: figures[index],
    })),
    sources,
  };
}

