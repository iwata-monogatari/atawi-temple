export function jikkaUrl(campaign: string, content?: string) {
  const params = new URLSearchParams({
    utm_source: "temple",
    utm_medium: "referral",
    utm_campaign: campaign,
  });
  if (content) params.set("utm_content", content);
  return `${FUDOSAN_JIKKA_URL}?${params.toString()}`;
}

