function evidenceAudit(sources: ResearchSource[], figures: ResearchFigure[]) {
  return "資料監査では、同じ情報を転載する複数ページを独立証拠として数えず、作成主体、成立時期、記述対象時点、公開目的を確認した。行政計画は現行政策と既往調査の要約、発掘報告は調査区内の物質記録、寺院ページは当事者の自己記述、現地写真は撮影時点の観察として能力を限定する。資料数が多いことを確度の高さへ置き換えず、異なる作成目的を持つ証拠が同じ主張を支えるかを評価した。" +
    sources.map((s, i) => `資料${i + 1}「${s.title}」は${s.publisher}の公開資料であり、${s.note} 確認日は${s.accessed}で、URLと表題を調査台帳へ保存した。この資料が直接扱わない寺院固有の沿革、災害時行動、信仰内容は推定へ拡張しない。数値は測定年、対象範囲、単位を伴う場合だけ比較し、一般向け概数と報告書の精査値に差があれば両方を記録する。記載が見つからない場合も事実不存在とせず、未収録、未公開、検索語不一致、資料欠損という代替説明を残す。後続調査では原資料の該当頁・図番号へ遡り、引用箇所の前後文脈と改訂履歴を確認する。`).join("") +
    figures.map((f, i) => `図版${i + 1}「${f.alt}」は2026年の現況記録であり、過去の河道、海岸線、建築年代、儀礼を外観だけで判定しない。写真には撮影位置、方向、対象、撮影日、編集履歴を付し、同名寺院や近隣施設の画像を代用しない。写っている堂宇・標識・道路の存在確認と、写っていない地下遺構・旧景観の復元を分ける。再撮影時は同じ位置と画角を可能な範囲で用い、建物修理、植生、道路、眺望の変化を比較する。`).join("") +
    "各主張には確認時点、根拠、代替説明、反証資料、確度を付し、新資料による変更履歴を保存する。複数資料が矛盾した場合は新しい資料を自動的に優先せず、それぞれが記述する時点と目的を比較する。結論は2026年7月時点の公開資料に限定し、寺蔵文書・未刊行調査・聞き取りが得られた際に、どの仮説が強まり、または棄却されるかを示す。これにより本文は完成した物語ではなく、検証経路を公開した更新可能な研究成果となる。";
}

function makeArticle(meta: Omit<ResearchArticle, "sections" | "sources">, headings: string[], topics: string[][], figures: ResearchFigure[], sources: ResearchSource[], method: string): ResearchArticle {
  return { ...meta, sections: headings.map((heading, i) => ({ heading: `${i + 1}　${heading}`, paragraphs: [...topics[i], ...(i === 5 ? [method, evidenceAudit(sources, figures), authorDisclosure] : [])], figure: figures[i] })), sources };
}

