function stableNumber(value: string) {
  return [...value].reduce((total, character) => ((total * 31) + character.charCodeAt(0)) >>> 0, 2166136261);
}

function makeUniqueIllustration(slug: string, index: number, label: string, caption: string, nodes: string[]) {
  const seed = stableNumber(`${slug}-${index}`);
  const leftX = 145 + (seed % 90);
  const leftY = 145 + ((seed >>> 3) % 120);
  const centerX = 420 + ((seed >>> 7) % 120);
  const centerY = 120 + ((seed >>> 11) % 165);
  const rightX = 715 + ((seed >>> 15) % 95);
  const rightY = 135 + ((seed >>> 19) % 135);
  const bend = 70 + ((seed >>> 23) % 110);
  return {
    label,
    caption,
    left: nodes[0],
    center: nodes[1],
    right: nodes[2],
    compositionId: `${slug}-composition-${index + 1}-${seed.toString(36)}`,
    leftX,
    leftY,
    centerX,
    centerY,
    rightX,
    rightY,
    pathD: `M${leftX + 92} ${leftY} Q${centerX - bend} ${centerY - bend} ${centerX - 92} ${centerY} M${centerX + 92} ${centerY} Q${rightX - bend} ${rightY + bend} ${rightX - 92} ${rightY}`,
  };
}

