function makeSections(
  texts: string[],
  headings: string[],
  usedFigures: ResearchFigure[],
  researchNotes: string[],
  conclusion: string,
  addenda: string[],
  disclosure: string,
): ResearchArticle["sections"] {
  return texts.map((text, index) => ({
    heading: headings[index],
    paragraphs: [
      text,
      `${researchNotes[index]} ${methodNotes[index]} ${deepNotes[index]}`,
      ...(index === 5 ? [conclusion, ...addenda, disclosure] : []),
    ],
    figure: usedFigures[index],
  }));
}

