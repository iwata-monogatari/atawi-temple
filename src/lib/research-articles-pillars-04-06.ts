function evidenceAudit(sources: ResearchSource[], figures: ResearchFigure[]) {
  const sourceReview = sources
    .map(
      (source, index) =>
        `資料${index + 1}「${source.title}」は${source.publisher}が公開し、本稿では${source.note} 同じ記述を別サイトが再掲していても独立証拠として加算せず、原資料へ遡って適用範囲を限定する。`,
    )
    .join("");
  const figureReview = figures
    .map(
      (figure, index) =>
        `図版${index + 1}「${figure.alt}」は現況を示す視覚資料である。撮影対象の存在確認には用いるが、写っていない過去の建築、制度、儀礼を外観から推定する証拠にはしない。`,
    )
    .join("");
  return `資料監査付記として、採用資料と図版の証明範囲を明記する。${sourceReview}${figureReview}この監査文は、情報量を出典件数へ置き換えず、各資料がどの主張を支え、何を支えないかを読者が再検証するための台帳である。`;
}

